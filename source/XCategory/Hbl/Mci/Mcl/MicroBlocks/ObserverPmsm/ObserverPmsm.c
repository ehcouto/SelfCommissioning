/**
 *  @brief      Tracking observer for PMSM motor.
 *  @details
 *
 * This module estimates the rotor flux speed and position starting from the position error calculated by the bemf observer according to the following equations:
 *
 *
 * \f[
 *  \begin{aligned}
 *     & \hat{\omega}(t) = \frac{\hat{d\theta}(t)}{dt} = K_{p}\cdot {\theta_{err}}  +  K_{i}\cdot {\int{\theta_{err}\cdot{dt}}}\\
 *     & \hat{\theta}(t) = {\int{\hat{\omega}(t)\cdot{dt}}}\\
 *  \end{aligned}
 * \f]
 *
 * where
 *
 * \f$ \hat{\omega}(t) \f$: estimated rotor flux speed
 *
 * \f$ \hat{\theta}(t) \f$: estimated rotor flux position
 *
 * \f$ \hat{\theta}_{err}(t) \f$: rotor flux estimated position error
 *
 * Discretizing the previous equations using backward Euler transformation:
 *
 * \f[
 *  \begin{aligned}
 *     & IntegralState(k) =  Ki*Ts\cdot{\theta_{err}(k)}  +  IntegralState(k-1)\\
 *     &\hat{\omega}(k) =  Kp\cdot{\theta_{err}(k)}  +  IntegralState(k)\\
 *     &\hat{\theta}(k) =  \hat{\theta}(k-1)  +  Ts\cdot {\omega}(k)\\
 *  \end{aligned}
 * \f]
 *
 * where
 *
 * Ts is the sampling period
 *
 *
 *  @param[in]      theta_err  = position estimation error in Q1.15 notation
 *  @param[in,out]  params = this structure contains parameters used for PI gains, estimated speed and position
 *  @return            theta_inj_short   = estimated position in Q1.15 notation
 */
mc_sint16 ObserverPmsm__TrackingObs(mc_sint16 theta_err, TRACKING_OBSERVER_PARAMS_TYPE *params)
{
    mc_sint32 temp32;
    mc_sint16 theta_inj_short;

    //Pi Execution -> Speed estimation
    params->Omega_Est =    Pi__PiRegNoAntiWindup((mc_sint32)theta_err, &params->State_PI, &params->Pi_Parameters);

    temp32 = MC_SCALE(params->Omega_Est,IQ30,IQ15); //17.15 = 2.30>>15

    //Angle update according the estimated speed
    theta_inj_short = (mc_sint16)Pi__IntegBE(temp32, &params->Theta_Est, &params->Integ_Parameters); // Thet_inj = Theta_inj_k + Ts*2*pi*SpeedEst

    return theta_inj_short;
}


