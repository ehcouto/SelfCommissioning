/**
 *  @brief      Back-EMF observer for PMSM motor.
 *  @details
 *
 * That observer estimates the D-Q components of back-emf generated by the permanent magnet flux on the stator windings according to the following equations:
 *
 *
 * \f[
 *  \begin{aligned}
 *     &\frac{\hat{dI_{d}}(t)}{dt}  =  -\frac{R}{L_{d}}\cdot {\hat{I}_{d}(t)} +\frac{1}{L_{d}}\cdot {\hat{E}_{d}(t)} + \frac{1}{L_{d}}\cdot {(V_{sd}(t)+ L_{q}w_{el}{I}_{q}(t))}\\
 *     &\frac{\hat{dI_{q}}(t)}{dt}  =  -\frac{R}{L_{d}}\cdot {\hat{I}_{q}(t)} +\frac{1}{L_{d}}\cdot {\hat{E}_{q}(t)} + \frac{1}{L_{d}}\cdot {(V_{sq}(t)- L_{q}w_{el}{I}_{d}(t))}\\
 *     &\frac{\hat{dE_{d}}(t)}{dt}  =  K_{i}\cdot {(I_{d}(t) - \hat{I}_{d}(t))} +K_{p}\cdot {(\frac{dI_{d}(t)}{dt} - \frac{\hat{dI_{d}}(t)}{dt})} \\
 *       &\frac{\hat{dE_{q}}(t)}{dt}  =  K_{i}\cdot {(I_{q}(t) - \hat{I}_{q}(t))} +K_{p}\cdot {(\frac{dI_{q}(t)}{dt} - \frac{\hat{dI_{q}}(t)}{dt})} \\
 *  \end{aligned}
 * \f]
 *
 * where
 *
 * \f$ V_{d} \f$: voltage on d axis
 *
 * \f$ V_{q} \f$: voltage on q axis
 *
 * \f$ I_{d} \f$: current on d axis
 *
 * \f$ I_{q} \f$: current on q axis
 *
 * \f$ \hat{I_{d}} \f$: estimated current on d axis
 *
 * \f$ \hat{I_{q}} \f$: estimated current on q axis
 *
 * \f$ \hat{E_{d}} \f$: estimated back-emf on d axis
 *
 * \f$ \hat{E_{q}} \f$: estimated back-emf on q axis
 *
 * \f$ w_{el} \f$: rotor flux speed
 *
 * The observer model uses the back-emf extended formula
 *
 *
 * \f[
 *  \begin{aligned}
 *     &E_{d}(t) = 0 \\
 *     &E_{q}(t) = E_{a} = {(L_{q}-L_{d})}\cdot \frac{{dI_{q}}(t)}{dt} +   {(L_{d}-L_{q})}\cdot {w_{el}I_{d}}  + w_{el}\cdot{Phi_{m}}\\
 *  \end{aligned}
 * \f]
 *
 *
 * The estimated back-emf depend on the d-q position estimation error
 *
 * \f[
 *  \begin{aligned}
 *     &\hat{E_{d}}(t) =  E_{a}\cdot{sin(Theta_{Err})} \\
 *     &\hat{E_{q}}(t) =  -E_{a}\cdot{cos(Theta_{Err})}\\
 *  \end{aligned}
 * \f]
 *
 * Tha estimated back-emfs are used to calculate the position estimation error.
 *
 * \f[
 *  \begin{aligned}
 *     &Theta_{Err} = atan(\frac{\hat{E}_{d}(t)}{-\hat{E_{q}}(t)}) =  atan(\frac{E_{a}\cdot{sin(Theta_{Err})}}{E_{a}\cdot{cos(Theta_{Err})}})  \\
 *  \end{aligned}
 * \f]
 *

 * Discretizing the previous equations using backward Euler transformation:
 *
 * \f[
 *  \begin{aligned}
 *     & IntegralStateD(k) =  Ki*Ts\cdot{(I_{d}(k) - \hat{I}_{d}(k-1))}  +  IntegralStateD(k-1)\\
 *     &\hat{E_{d}}(k)  =  (Kp\cdot{(I_{d}(k) - \hat{I}_{d}(k-1))}  +  IntegralStateD(k))\\
 *     &\hat{I_{d}}(k)  =  (Ld/(Ld+Ts\cdot{Rs}))\cdot {\hat{I}_{d}(k-1)}  +  (Ts/(Ld+Ts\cdot{Rs}))\cdot {E_{d}(k)} + (Ts/(Ld+Ts\cdot{Rs}))\cdot {V_{d}(k)}  +  (Ts\cdot{Lq}/(Ld+Ts\cdot{Rs}))\cdot {L_{q}w_{el}(k){I}_{q}(k)} \\
 *     & IntegralStateQ(k) =  Ki*Ts\cdot{(I_{d}(k) - \hat{I}_{d}(k-1))}  +  IntegralStateQ(k-1)\\
 *     &\hat{E_{q}}(k)  =  (Kp\cdot{(I_{q}(k) - \hat{I}_{q}(k-1))}  +  IntegralStateQ(k))\\
 *     &\hat{I_{d}}(k)  =  (Ld/(Ld+Ts\cdot{Rs}))\cdot {\hat{I}_{q}(k-1)}  +  (Ts/(Ld+Ts\cdot{Rs}))\cdot {E_{q}(k)} + (Ts/(Ld+Ts\cdot{Rs}))\cdot {V_{d}(k)}  -  (Ts\cdot{Lq}/(Ld+Ts\cdot{Rs}))\cdot {L_{q}w_{el}(k){I}_{q}(k)} \\
 *  \end{aligned}
 * \f]
 *
 * where
 *
 * Ts is the sampling period
 *
 *  @param[in]      i_dq   = motor current components in d-q reference frame (aligned with rotor flux position)
 *  @param[in]      v_dq   = motor voltage components in d-q reference frame (aligned with rotor flux position)
 *  @param[in]      OmegaFlux   = rotor electrical speed in Q17.15 notation
 *  @param[in,out]      params = this structure contains parameters used for back-emf equation, rotor-flux position, PI gains, estimated quantities [current/bemf]
 */
void ObserverPmsm__BemfObsDQ(DQ_COOR_SYST_TYPE* i_dq, DQ_COOR_SYST_TYPE* v_dq, mc_sint32 omega_flux, BEMF_OBSERVER_PARAMS_TYPE* params)
{

    mc_sint32 id_error;
    mc_sint32 iq_error;
    mc_sint32 bemf_d_15;
    mc_sint32 bemf_q_15;
    mc_sint64 temp64;

    //------------------------------------------------------------------------
    //               Calculation params.BemfEst.D
    // ------------------------------------------------------------------------
    id_error = i_dq->D - MC_SCALE(params->Current_Est.D,IQ30,IQ15);

    params->Bemf_Est.D =    Pi__PiRegNoAntiWindup(id_error, &params->Pi_States.State_D, &params->Pi_Parameters);

    // ------------------------------------------------------------------------
    //               Calculation params.CurrentEst.D
    // ------------------------------------------------------------------------
    //params->CurrentEst.D = params->Icoeff*params->CurrentEst.D    +    params->Ecoeff*params->BemfEst.D  +  params->Ucoeff*v_dq->D     + params->WIcoeff*w_el*i_dq->Q;
    //temp64 = (sint64)IQMATH__I2Q30MULI17Q15_I2Q30(params->Icoeff, params->CurrentEst.D);
    temp64 = MC_MULT_LL_LL(params->I_Coeff, params->Current_Est.D, IQ15, IQ30, IQ30);
    temp64 = temp64 + MC_MULT_LL_LL(params->E_Coeff, params->Bemf_Est.D,IQ14,IQ30,IQ30);
    temp64 = temp64 + (mc_sint64)params->U_Coeff * (mc_sint64)v_dq->D;
    temp64 = temp64 + MC_MULT_LL_LL(params->WI_Coeff, ((mc_sint64)omega_flux * (mc_sint64)i_dq->Q), IQ14, IQ30, IQ30);

    //saturation
    if (temp64 > (mc_sint64)MC_ONE_IQ30)
    {
        params->Current_Est.D = MC_ONE_IQ30;
    }
    else if (temp64 < (mc_sint64)MC_MINUS_ONE_IQ30)
    {
        params->Current_Est.D = MC_MINUS_ONE_IQ30;
    }
    else
    {
        params->Current_Est.D = (mc_sint32)temp64;
    }



    // ------------------------------------------------------------------------
    //               Calculation params.BemfEst.Q
    // ------------------------------------------------------------------------
    iq_error = i_dq->Q - MC_SCALE(params->Current_Est.Q,IQ30, IQ15);

    params->Bemf_Est.Q =    Pi__PiRegNoAntiWindup(iq_error, &params->Pi_States.State_Q, &params->Pi_Parameters);


    //------------------------------------------------------------------------
    //               Calculation params.CurrentEst.Q
    // ------------------------------------------------------------------------
    //params->CurrentEst.Q = params->Icoeff*params->CurrentEst.Q    +    params->Ecoeff*params->BemfEst.Q +   params->Ucoeff*v_dq->Q     - params->WIcoeff*w_el*i_dq->D;
    //temp64 = (sint64)IQMATH__I2Q30MULI17Q15_I2Q30(params->Icoeff, params->CurrentEst.Q);
    temp64 = MC_MULT_LL_LL(params->I_Coeff, params->Current_Est.Q, IQ15, IQ30, IQ30);
    temp64 = temp64 + MC_MULT_LL_LL(params->E_Coeff, params->Bemf_Est.Q,IQ14, IQ30, IQ30);
    temp64 = temp64 + (mc_sint64)params->U_Coeff *(mc_sint64)v_dq->Q;
    temp64 = temp64 - MC_MULT_LL_LL(params->WI_Coeff, ((mc_sint64)omega_flux * (mc_sint64)i_dq->D),IQ14, IQ30, IQ30);

    //saturation
    if (temp64 > (mc_sint64)MC_ONE_IQ30)
    {
        params->Current_Est.Q = MC_MINUS_ONE_IQ30;
    }
    else if (temp64 < (mc_sint64)MC_MINUS_ONE_IQ30)
    {
        params->Current_Est.Q = MC_MINUS_ONE_IQ30;
    }
    else
    {
        params->Current_Est.Q = (mc_sint32)temp64;
    }



    //Position Error calculation
    bemf_d_15 = MC_SCALE(params->Bemf_Est.D,IQ30,IQ15);   //17.15 = 2.30>>15
    bemf_q_15 = MC_SCALE(params->Bemf_Est.Q,IQ30,IQ15);     //17.15 = 2.30>>15

    params->Theta_Flux_Error = (mc_sint16)MC_ATAN2(-bemf_q_15, bemf_d_15);

}



