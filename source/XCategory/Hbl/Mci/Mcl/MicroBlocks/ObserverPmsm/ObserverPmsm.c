/**
 *  @brief      Startup observer for PMSM motor.
 *  @details
 *
 * That observer estimates two electrical speeds according to the following equations:
 *
 *
 * \f[
 *  \begin{aligned}
 *     &\hat{\omega_d} = V_d \cdot \left[-\frac{1}{L_s I_q}\right]\\
 *     &\hat{\omega_d} = (V_q - V_{qAlign}) \cdot \frac{1}{\varphi_m}\\
 *  \end{aligned}
 * \f]
 *
 * where
 *
 * \f$ V_{d} \f$: voltage on d axis
 *
 * \f$ V_{q} \f$: voltage on q axis
 *
 * \f$ I_{q} \f$: current on q axis
 *
 * \f$ \hat{omega_{d}} \f$: estimated speed based on d axis equation
 *
 * \f$ \hat{omega_{q}} \f$: estimated speed based on q axis equation
 *
 * \f$ -\left[\frac{1}{L_s I_q}\right] = K1 \f$
 *
 * \f$ \frac{1}{\varphi_m} = K2 \f$
 *
 * The error is given by:
 *
 * \f$ \omega_{error} = \hat{\omega_{d}} - \hat{\omega_{q}} \f$
 *
 *
 *
 *  @param[in]      v_dq   = motor voltage components in d-q reference frame (aligned with rotor flux position)
 *  @param[in,out]  omega_startup  = estimated motor electrical speed (d and q equations)
 *  @param[in]      vq_alignment   = measured voltage during alignment phase (equal to \f$ R_s I_q \f$ )
 *  @param[in]      params = this structure contains parameters used for startup observer K1, K2
 *  @return         error  = \f$ \hat{\omega_{d}} - \hat{\omega_{q}} \f$
 */
mc_sint32 ObserverPmsm__StartupObs(DQ_COOR_SYST_TYPE* v_dq, mc_sint32 vq_alignment, STARTUP_OBSERVER_PARAMS_TYPE* params)
{
    mc_sint32 temp;
    mc_sint32 error;
    DQ_COOR_SYST_TYPE v_dq_sobs;
    ALPHA_BETA_COOR_SYST_TYPE v_alphabeta_sobs;
    mc_sint32 theta_est;
    SIN_COS_TYPE    sin_cos_theta_flux;


    // calculation of Vs d-q components on estimated position by startup observer
    theta_est = MC_SCALE(params->Theta_Est_Q, IQ30, IQ15);

    MC_SINCOS(theta_est, &sin_cos_theta_flux);

    ClrkPark__InversePark(v_dq, &v_alphabeta_sobs, &sin_cos_theta_flux);

    theta_est = MC_SCALE(params->Theta_Est, IQ30, IQ15);

    MC_SINCOS(theta_est, &sin_cos_theta_flux);

    ClrkPark__DirectPark(&v_alphabeta_sobs, &v_dq_sobs, &sin_cos_theta_flux);




    // Startup observer equation

    // Omega d-calculation
    params->Omega_Est_D = MC_MULT_L(v_dq_sobs.D,params->K_1, IQ15, IQ15, IQ15);  //w_d = Vd/(Lq*CurrentStartup)

    // Omega q-calculation
    temp = v_dq_sobs.Q - vq_alignment;
    params->Omega_Est_Q = MC_MULT_L(temp, params->K_2, IQ15, IQ15, IQ15);       //w_q = (Vq - Rs*CurrentStartup)/(Phim)


    // angle estimation angle calculation
    error = params->Omega_Est_D - params->Omega_Est_Q;


    if(params->Omega_Est_D > STARTUP_OBSERVER_MIN_SPEED)
    {
        error = MathCalc__Arctan2(params->Omega_Est_D,error);
    }

    // Pi execution to reduce the error angle
    params->Omega_Est = Pi__PiRegBackCalc(error, &params->State_PI, &params->Pi_Parameters);


    //Angle update according the estimated speed
    theta_est = (mc_sint16)Pi__IntegBE(params->Omega_Est, &params->Theta_Est, &params->Integ_Parameters); // Thet_inj = Theta_inj_k + Ts*2*pi*SpeedEst

    //Angle update according the estimated speed
    theta_est = (mc_sint16)Pi__IntegBE(params->Omega_Est_Q, &params->Theta_Est_Q, &params->Integ_Parameters); // Thet_inj = Theta_inj_k + Ts*2*pi*SpeedEst


    return theta_est;

}


void ObserverPmsm__BemfObsDQF(DQ_COOR_SYST_F_TYPE* i_dq, DQ_COOR_SYST_F_TYPE* v_dq, float32 omega_flux, BEMF_OBSERVER_PARAMS_F_TYPE* params)
{
    float32 temp;

    //------------------------------------------------------------------------
    //               Calculation params.BemfEst.D
    // ------------------------------------------------------------------------
    params->Pi_D.Err = i_dq->D - params->Current_Est.D;
    Pi__PiRegNoAntiWindupF(&params->Pi_D);
    params->Bemf_Est.D = params->Pi_D.Out;

    // ------------------------------------------------------------------------
    //               Calculation params.CurrentEst.D
    // ------------------------------------------------------------------------
    temp = params->I_Coeff * params->Current_Est.D;
    temp = temp + params->E_Coeff * params->Bemf_Est.D;
    temp = temp + params->U_Coeff * v_dq->D;
    temp = temp + params->WI_Coeff * (omega_flux * i_dq->Q);

    params->Current_Est.D = temp;



    // ------------------------------------------------------------------------
    //               Calculation params.BemfEst.Q
    // ------------------------------------------------------------------------
    params->Pi_Q.Err = i_dq->Q - params->Current_Est.Q;
    Pi__PiRegNoAntiWindupF(&params->Pi_Q);
    params->Bemf_Est.Q = params->Pi_Q.Out;

    //------------------------------------------------------------------------
    //               Calculation params.CurrentEst.Q
    // ------------------------------------------------------------------------
    temp = params->I_Coeff * params->Current_Est.Q;
    temp = temp + (params->E_Coeff * params->Bemf_Est.Q);
    temp = temp + (params->U_Coeff * v_dq->Q);
    temp = temp - (params->WI_Coeff * (omega_flux * i_dq->D));

    params->Current_Est.Q = temp;

    //Position Error calculation
    params->Theta_Flux_Error = MathCalc__Arctan2F(-(params->Bemf_Est.Q), params->Bemf_Est.D);
}

float32 ObserverPmsm__TrackingObsF(float32 theta_err, TRACKING_OBSERVER_PARAMS_F_TYPE *params)
{
    //Pi Execution -> Speed estimation
    params->Pi.Err = theta_err;
    Pi__PiRegNoAntiWindupF(&params->Pi);
    params->Omega_Est = params->Pi.Out;

    //Angle update according the estimated speed
    params->Theta_Est = params->Theta_Est + params->Omega_Est * (params->Integ_Parameters.Ki); // Thet_inj = Theta_inj_k + Ts*SpeedEst

    if(params->Theta_Est > PI)
    {
        params->Theta_Est -= (2.0f * PI);
    }

    if(params->Theta_Est < (-PI))
    {
        params->Theta_Est += (2.0f * PI);
    }

    return params->Theta_Est;
}


float32 ObserverPmsm__StartupObsF(DQ_COOR_SYST_F_TYPE* v_dq, float32 vq_alignment, STARTUP_OBSERVER_PARAMS_F_TYPE* params)
{
    float32 temp;
    float32 error;
    DQ_COOR_SYST_F_TYPE v_dq_sobs;
    ALPHA_BETA_COOR_SYST_F_TYPE v_alphabeta_sobs;
    SIN_COS_F_TYPE    sin_cos_theta_flux;

    // calculation of Vs d-q components on estimated position by startup observer
    MC_SINCOS_F(params->Theta_Est_Q, &sin_cos_theta_flux);
    ClrkPark__InverseParkF(v_dq, &v_alphabeta_sobs, &sin_cos_theta_flux);

    MC_SINCOS_F(params->Theta_Est, &sin_cos_theta_flux);
    ClrkPark__DirectParkF(&v_alphabeta_sobs, &v_dq_sobs, &sin_cos_theta_flux);


    // Startup observer equation

    // Omega d-calculation
    params->Omega_Est_D = v_dq_sobs.D * params->K_1;  //w_d = Vd/(Lq*CurrentStartup)

    // Omega q-calculation
    temp = v_dq_sobs.Q - vq_alignment;
    params->Omega_Est_Q = temp * params->K_2;       //w_q = (Vq - Rs*CurrentStartup)/(Phim)

    // angle estimation angle calculation
    error = params->Omega_Est_D - params->Omega_Est_Q;

    // Pi execution to reduce the error angle
    params->Pi.Err = error;
    Pi__CalcPiBackCalcF(&params->Pi);
    params->Omega_Est = params->Pi.Out;

    //Angle update according the estimated speed
    params->Theta_Est = params->Theta_Est + params->Omega_Est * (params->Integ_Parameters.Ki); // Thet_inj = Theta_inj_k + Ts*SpeedEst

    //Angle update according the estimated speed
    params->Theta_Est_Q = params->Theta_Est_Q + params->Omega_Est_Q * (params->Integ_Parameters.Ki); // Thet_inj = Theta_inj_k + Ts*SpeedEst

    return params->Theta_Est_Q;
}
